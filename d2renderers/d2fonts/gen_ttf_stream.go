//go:build ignore

// gen_ttf_stream writes ttf_stream.br and ttf_stream_table.go from ttf/*.ttf.
// Run it with go generate in this directory after adding, removing or
// changing a face; TestBundledTTFStream fails until the committed stream
// matches the TTFs again.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"

	"github.com/andybalholm/brotli"
)

func main() {
	paths, err := filepath.Glob("ttf/*.ttf")
	if err != nil {
		log.Fatal(err)
	}
	if len(paths) == 0 {
		log.Fatal("no ttf/*.ttf here; run go generate in d2renderers/d2fonts")
	}
	sort.Strings(paths)

	var faces, table bytes.Buffer
	table.WriteString("// Code generated by gen_ttf_stream.go; DO NOT EDIT.\n\npackage d2fonts\n\n")
	table.WriteString("// bundledTTFStreamFaces lists the faces of ttf_stream.br in stream order with\n")
	table.WriteString("// their lengths in bytes.\n")
	table.WriteString("var bundledTTFStreamFaces = [...]bundledTTFStreamFace{\n")
	for _, path := range paths {
		ttf, err := os.ReadFile(path)
		if err != nil {
			log.Fatal(err)
		}
		faces.Write(ttf)
		fmt.Fprintf(&table, "{%q, %d},\n", filepath.Base(path), len(ttf))
	}
	table.WriteString("}\n")

	// The window is the smallest that spans all faces, so that a face can
	// refer to any earlier one and the decoder's ring buffer stays as small
	// as that allows.
	lgwin := 10
	for (1<<lgwin)-16 < faces.Len() {
		lgwin++
	}
	if lgwin > 24 {
		log.Fatalf("%d bytes of faces do not fit a brotli window", faces.Len())
	}
	var stream bytes.Buffer
	w := brotli.NewWriterOptions(&stream, brotli.WriterOptions{Quality: 11, LGWin: lgwin})
	if _, err := w.Write(faces.Bytes()); err != nil {
		log.Fatal(err)
	}
	if err := w.Close(); err != nil {
		log.Fatal(err)
	}

	source, err := format.Source(table.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("ttf_stream.br", stream.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("ttf_stream_table.go", source, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("ttf_stream.br: %d faces, %d bytes, %d compressed (window 2^%d)\n", len(paths), faces.Len(), stream.Len(), lgwin)
}
